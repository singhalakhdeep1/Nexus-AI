"use client";

import { useQuery, useMutation, useQueryClient, useInfiniteQuery } from "@tanstack/react-query";
import { createClient } from "@/lib/supabase/client";
import type { Task, TaskFilters, CreateTaskInput, UpdateTaskInput } from "@/types";

const supabase = createClient();

// ── Query Keys ─────────────────────────────────────────────
export const taskKeys = {
    all: (projectId: string) => ["tasks", projectId] as const,
    filtered: (projectId: string, filters: TaskFilters) =>
        ["tasks", projectId, filters] as const,
    detail: (id: string) => ["tasks", "detail", id] as const,
    comments: (taskId: string) => ["tasks", "comments", taskId] as const,
};

// ── Fetch tasks for a project ──────────────────────────────
export function useTasks(projectId: string, filters: TaskFilters = {}) {
    return useQuery({
        queryKey: taskKeys.filtered(projectId, filters),
        queryFn: async () => {
            let query = supabase
                .from("tasks")
                .select(`
          *,
          assignee:profiles!tasks_assignee_id_fkey(id, full_name, avatar_url),
          reporter:profiles!tasks_reporter_id_fkey(id, full_name, avatar_url),
          labels:task_labels(label:labels(*))
        `)
                .eq("project_id", projectId)
                .is("parent_task_id", null) // top-level tasks only
                .order("sort_order", { ascending: true });

            if (filters.status?.length) {
                query = query.in("status", filters.status);
            }
            if (filters.priority?.length) {
                query = query.in("priority", filters.priority);
            }
            if (filters.assignee_id?.length) {
                query = query.in("assignee_id", filters.assignee_id);
            }
            if (filters.sprint_id) {
                query = query.eq("sprint_id", filters.sprint_id);
            }
            if (filters.search) {
                query = query.textSearch("title", filters.search, { type: "websearch" });
            }

            const { data, error } = await query;
            if (error) throw error;

            // Flatten label join
            return data.map((task) => ({
                ...task,
                labels: task.labels?.map((tl: { label: unknown }) => tl.label) ?? [],
            })) as Task[];
        },
        staleTime: 1000 * 30, // 30 seconds — near real-time
        enabled: !!projectId,
    });
}

// ── Fetch task detail ──────────────────────────────────────
export function useTask(taskId: string) {
    return useQuery({
        queryKey: taskKeys.detail(taskId),
        queryFn: async () => {
            const { data, error } = await supabase
                .from("tasks")
                .select(`
          *,
          assignee:profiles!tasks_assignee_id_fkey(id, full_name, avatar_url),
          reporter:profiles!tasks_reporter_id_fkey(id, full_name, avatar_url),
          labels:task_labels(label:labels(*)),
          subtasks:tasks!parent_task_id(
            id, identifier, title, status, priority, assignee_id,
            assignee:profiles!tasks_assignee_id_fkey(id, full_name, avatar_url)
          )
        `)
                .eq("id", taskId)
                .single();

            if (error) throw error;
            return {
                ...data,
                labels: data.labels?.map((tl: { label: unknown }) => tl.label) ?? [],
            } as Task;
        },
        enabled: !!taskId,
    });
}

// ── Create task ────────────────────────────────────────────
export function useCreateTask(projectId: string) {
    const queryClient = useQueryClient();

    return useMutation({
        mutationFn: async (input: CreateTaskInput & { reporter_id: string; parent_task_id?: string }) => {
            const { label_ids, ...taskData } = input;

            const { data: task, error } = await supabase
                .from("tasks")
                .insert({
                    project_id: projectId,
                    identifier: "", // auto-generated by DB trigger
                    ...taskData,
                })
                .select()
                .single();

            if (error) throw error;

            // Attach labels
            if (label_ids?.length) {
                await supabase.from("task_labels").insert(
                    label_ids.map((label_id) => ({ task_id: task.id, label_id }))
                );
            }

            return task as Task;
        },
        onSuccess: () => {
            queryClient.invalidateQueries({ queryKey: taskKeys.all(projectId) });
        },
    });
}

// ── Update task ────────────────────────────────────────────
export function useUpdateTask(projectId: string) {
    const queryClient = useQueryClient();

    return useMutation({
        mutationFn: async ({ id, label_ids, ...updates }: UpdateTaskInput) => {
            const { data, error } = await supabase
                .from("tasks")
                .update(updates)
                .eq("id", id)
                .select()
                .single();

            if (error) throw error;

            // Update labels if provided
            if (label_ids !== undefined) {
                await supabase.from("task_labels").delete().eq("task_id", id);
                if (label_ids.length > 0) {
                    await supabase.from("task_labels").insert(
                        label_ids.map((label_id) => ({ task_id: id, label_id }))
                    );
                }
            }

            return data as Task;
        },
        onMutate: async (updated) => {
            // Optimistic update
            await queryClient.cancelQueries({ queryKey: taskKeys.all(projectId) });
            const previousTasks = queryClient.getQueryData(taskKeys.all(projectId));

            queryClient.setQueriesData(
                { queryKey: taskKeys.all(projectId) },
                (old: Task[] | undefined) =>
                    old?.map((t) => (t.id === updated.id ? { ...t, ...updated } : t))
            );

            return { previousTasks };
        },
        onError: (_err, _updated, context) => {
            if (context?.previousTasks) {
                queryClient.setQueryData(taskKeys.all(projectId), context.previousTasks);
            }
        },
        onSettled: () => {
            queryClient.invalidateQueries({ queryKey: taskKeys.all(projectId) });
        },
    });
}

// ── Delete task ────────────────────────────────────────────
export function useDeleteTask(projectId: string) {
    const queryClient = useQueryClient();

    return useMutation({
        mutationFn: async (taskId: string) => {
            const { error } = await supabase.from("tasks").delete().eq("id", taskId);
            if (error) throw error;
            return taskId;
        },
        onSuccess: () => {
            queryClient.invalidateQueries({ queryKey: taskKeys.all(projectId) });
        },
    });
}

// ── Fetch comments for a task ─────────────────────────────
export function useComments(taskId: string) {
    return useQuery({
        queryKey: taskKeys.comments(taskId),
        queryFn: async () => {
            const { data, error } = await supabase
                .from("comments")
                .select(`
          *,
          author:profiles!comments_author_id_fkey(id, full_name, avatar_url)
        `)
                .eq("task_id", taskId)
                .is("parent_comment_id", null)
                .order("created_at", { ascending: true });

            if (error) throw error;
            return data;
        },
        enabled: !!taskId,
    });
}

// ── Add comment ────────────────────────────────────────────
export function useAddComment(taskId: string) {
    const queryClient = useQueryClient();

    return useMutation({
        mutationFn: async ({
            content,
            author_id,
            parent_comment_id,
        }: {
            content: string;
            author_id: string;
            parent_comment_id?: string;
        }) => {
            const { data, error } = await supabase
                .from("comments")
                .insert({ task_id: taskId, content, author_id, parent_comment_id })
                .select(`*, author:profiles!comments_author_id_fkey(id, full_name, avatar_url)`)
                .single();

            if (error) throw error;
            return data;
        },
        onSuccess: () => {
            queryClient.invalidateQueries({ queryKey: taskKeys.comments(taskId) });
        },
    });
}
